"""
GTM Strategy Quality Metrics.

This module provides metrics for evaluating the quality and completeness
of the Go-to-Market strategy generated by the Strategist agent.
"""

from typing import Dict, Any, List
from dataclasses import dataclass


@dataclass
class GTMQualityScore:
    """GTM strategy quality score."""

    overall_score: float  # 0-1
    completeness_score: float  # 0-1
    specificity_score: float  # 0-1
    actionability_score: float  # 0-1

    # Component scores
    has_target_audience: bool
    has_value_proposition: bool
    has_pricing_strategy: bool
    has_distribution_channels: bool
    has_marketing_hooks: bool
    has_competitive_advantages: bool
    has_key_risks: bool
    has_success_metrics: bool

    # Quality indicators
    target_audience_length: int
    value_proposition_length: int
    num_distribution_channels: int
    num_marketing_hooks: int
    num_competitive_advantages: int
    num_key_risks: int
    num_success_metrics: int

    details: Dict[str, Any]


def evaluate_gtm_completeness(gtm_plan: Dict[str, Any]) -> float:
    """
    Evaluate completeness of GTM strategy.

    Checks presence of all required components.

    Args:
        gtm_plan: GTM plan from strategist agent

    Returns:
        Completeness score from 0-1
    """
    required_fields = [
        'target_audience',
        'value_proposition',
        'pricing_strategy',
        'distribution_channels',
        'marketing_hooks',
        'competitive_advantages',
        'key_risks',
        'success_metrics',
    ]

    present_count = 0
    for field in required_fields:
        value = gtm_plan.get(field)

        # Check if field is present and non-empty
        if value:
            if isinstance(value, str) and len(value.strip()) > 10:
                present_count += 1
            elif isinstance(value, list) and len(value) > 0:
                present_count += 1

    return present_count / len(required_fields)


def evaluate_gtm_specificity(gtm_plan: Dict[str, Any]) -> float:
    """
    Evaluate specificity of GTM strategy.

    Checks if the strategy contains specific, actionable details
    rather than generic statements.

    Args:
        gtm_plan: GTM plan from strategist agent

    Returns:
        Specificity score from 0-1
    """
    specificity_score = 0.0
    max_score = 8.0

    # Target audience specificity (0-1)
    target_audience = gtm_plan.get('target_audience', '')
    if len(target_audience) > 100:
        specificity_score += 1.0
    elif len(target_audience) > 50:
        specificity_score += 0.5

    # Value proposition specificity (0-1)
    value_prop = gtm_plan.get('value_proposition', '')
    if len(value_prop) > 100:
        specificity_score += 1.0
    elif len(value_prop) > 50:
        specificity_score += 0.5

    # Pricing strategy detail (0-1)
    pricing = gtm_plan.get('pricing_strategy', '')
    if len(pricing) > 50:
        specificity_score += 1.0
    elif len(pricing) > 20:
        specificity_score += 0.5

    # Number of distribution channels (0-1)
    channels = gtm_plan.get('distribution_channels', [])
    if len(channels) >= 3:
        specificity_score += 1.0
    elif len(channels) >= 2:
        specificity_score += 0.5

    # Number of marketing hooks (0-1)
    hooks = gtm_plan.get('marketing_hooks', [])
    if len(hooks) >= 4:
        specificity_score += 1.0
    elif len(hooks) >= 2:
        specificity_score += 0.5

    # Number of competitive advantages (0-1)
    advantages = gtm_plan.get('competitive_advantages', [])
    if len(advantages) >= 3:
        specificity_score += 1.0
    elif len(advantages) >= 2:
        specificity_score += 0.5

    # Number of key risks (0-1)
    risks = gtm_plan.get('key_risks', [])
    if len(risks) >= 3:
        specificity_score += 1.0
    elif len(risks) >= 2:
        specificity_score += 0.5

    # Number of success metrics (0-1)
    metrics = gtm_plan.get('success_metrics', [])
    if len(metrics) >= 4:
        specificity_score += 1.0
    elif len(metrics) >= 2:
        specificity_score += 0.5

    return specificity_score / max_score


def evaluate_gtm_actionability(gtm_plan: Dict[str, Any]) -> float:
    """
    Evaluate actionability of GTM strategy.

    Checks if the strategy provides concrete, actionable steps
    and measurable metrics.

    Args:
        gtm_plan: GTM plan from strategist agent

    Returns:
        Actionability score from 0-1
    """
    actionability_score = 0.0
    max_score = 5.0

    # Has timeline (0-1)
    timeline = gtm_plan.get('timeline', '')
    if timeline and len(timeline) > 20:
        actionability_score += 1.0

    # Has specific distribution channels (0-1)
    channels = gtm_plan.get('distribution_channels', [])
    if len(channels) > 0:
        # Check for specific channel names (not generic)
        specific_keywords = ['instagram', 'facebook', 'linkedin', 'google', 'email',
                            'seo', 'content', 'partner', 'direct', 'retail']
        has_specific = any(
            any(keyword in channel.lower() for keyword in specific_keywords)
            for channel in channels
        )
        if has_specific:
            actionability_score += 1.0
        else:
            actionability_score += 0.5

    # Has measurable success metrics (0-1)
    metrics = gtm_plan.get('success_metrics', [])
    if len(metrics) >= 3:
        # Check for quantitative keywords
        quantitative_keywords = ['%', 'number', 'rate', 'growth', 'revenue',
                                'customers', 'users', 'mrr', 'arr', 'ltv', 'cac']
        has_quantitative = any(
            any(keyword in metric.lower() for keyword in quantitative_keywords)
            for metric in metrics
        )
        if has_quantitative:
            actionability_score += 1.0
        else:
            actionability_score += 0.5

    # Has identified key risks (0-1)
    risks = gtm_plan.get('key_risks', [])
    if len(risks) >= 2:
        actionability_score += 1.0
    elif len(risks) >= 1:
        actionability_score += 0.5

    # Has competitive advantages (0-1)
    advantages = gtm_plan.get('competitive_advantages', [])
    if len(advantages) >= 2:
        actionability_score += 1.0
    elif len(advantages) >= 1:
        actionability_score += 0.5

    return actionability_score / max_score


def evaluate_gtm_quality(result: Dict[str, Any]) -> GTMQualityScore:
    """
    Evaluate overall GTM strategy quality.

    Args:
        result: Complete analysis result with strategist_plan

    Returns:
        GTMQualityScore with detailed metrics
    """
    gtm_plan = result.get('strategist_plan', {})

    # Calculate component scores
    completeness = evaluate_gtm_completeness(gtm_plan)
    specificity = evaluate_gtm_specificity(gtm_plan)
    actionability = evaluate_gtm_actionability(gtm_plan)

    # Calculate overall score (weighted average)
    overall = (completeness * 0.4 + specificity * 0.35 + actionability * 0.25)

    # Component presence
    has_target_audience = bool(gtm_plan.get('target_audience'))
    has_value_proposition = bool(gtm_plan.get('value_proposition'))
    has_pricing_strategy = bool(gtm_plan.get('pricing_strategy'))
    has_distribution_channels = bool(gtm_plan.get('distribution_channels'))
    has_marketing_hooks = bool(gtm_plan.get('marketing_hooks'))
    has_competitive_advantages = bool(gtm_plan.get('competitive_advantages'))
    has_key_risks = bool(gtm_plan.get('key_risks'))
    has_success_metrics = bool(gtm_plan.get('success_metrics'))

    # Quality indicators
    target_audience_length = len(gtm_plan.get('target_audience', ''))
    value_proposition_length = len(gtm_plan.get('value_proposition', ''))
    num_distribution_channels = len(gtm_plan.get('distribution_channels', []))
    num_marketing_hooks = len(gtm_plan.get('marketing_hooks', []))
    num_competitive_advantages = len(gtm_plan.get('competitive_advantages', []))
    num_key_risks = len(gtm_plan.get('key_risks', []))
    num_success_metrics = len(gtm_plan.get('success_metrics', []))

    return GTMQualityScore(
        overall_score=overall,
        completeness_score=completeness,
        specificity_score=specificity,
        actionability_score=actionability,
        has_target_audience=has_target_audience,
        has_value_proposition=has_value_proposition,
        has_pricing_strategy=has_pricing_strategy,
        has_distribution_channels=has_distribution_channels,
        has_marketing_hooks=has_marketing_hooks,
        has_competitive_advantages=has_competitive_advantages,
        has_key_risks=has_key_risks,
        has_success_metrics=has_success_metrics,
        target_audience_length=target_audience_length,
        value_proposition_length=value_proposition_length,
        num_distribution_channels=num_distribution_channels,
        num_marketing_hooks=num_marketing_hooks,
        num_competitive_advantages=num_competitive_advantages,
        num_key_risks=num_key_risks,
        num_success_metrics=num_success_metrics,
        details={
            'completeness_breakdown': {
                'target_audience': has_target_audience,
                'value_proposition': has_value_proposition,
                'pricing_strategy': has_pricing_strategy,
                'distribution_channels': has_distribution_channels,
                'marketing_hooks': has_marketing_hooks,
                'competitive_advantages': has_competitive_advantages,
                'key_risks': has_key_risks,
                'success_metrics': has_success_metrics,
            },
            'viability_score': gtm_plan.get('viability_score', 0),
        }
    )
